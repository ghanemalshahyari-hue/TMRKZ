#!/usr/bin/env sh
# TMRKZ's demo HR source (owner, 11 Nov 2026; ADR-057), as TNQL's: starts «tmrkz-hr-demo-oracle» (Oracle Database Free) next
# to the one application and fills it with TNQL's synthetic organisation and 200,000 synthetic people, read through the
# views HR_ENV_UNITS_AI and HR_PRS_EMPLOYEES_ALL by the read-only account TMRKZ_HR. Secrets are generated once into
# ops/hr-demo/.generated/oracle_hr.env (never committed). Re-running rebuilds the data the same way (fixed seed).
#   sh ops/hr-demo/up.sh            build (first start takes a few minutes)
#   sh ops/hr-demo/up.sh --verify   verification queries only
set -eu
export MSYS_NO_PATHCONV=1
cd "$(dirname "$0")"
G=.generated
mkdir -p "$G"
rand() { head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c "$1"; }
if [ ! -f "$G/oracle_hr.env" ]; then
  umask 077
  cat > "$G/oracle_hr.env" <<EOF
# generated by ops/hr-demo/up.sh — demo only, never a production secret
ORACLE_HR_HOST=tmrkz-hr-demo-oracle
ORACLE_HR_PORT=1521
ORACLE_HR_SERVICE=FREEPDB1
ORACLE_SYSTEM_PASSWORD=S$(rand 20)
ORACLE_HR_SCHEMA=HR_AI
ORACLE_HR_SCHEMA_PASSWORD=H$(rand 20)
ORACLE_MOVER_USER=TMRKZ_HR
ORACLE_MOVER_PASSWORD=R$(rand 20)
EOF
fi
docker network inspect tmrkz-mover_internal >/dev/null 2>&1 || { echo "[hr-demo] start TMRKZ first (sh start.sh)" >&2; exit 2; }
docker compose -p tmrkz-hr-demo --env-file "$G/oracle_hr.env" -f compose.yml up -d
i=0
until [ "$(docker inspect -f '{{.State.Health.Status}}' tmrkz-hr-demo-oracle 2>/dev/null)" = healthy ]; do
  i=$((i + 1)); [ $i -gt 80 ] && { echo "[hr-demo] Oracle did not become healthy" >&2; exit 1; }; sleep 5
done
echo "[hr-demo] Oracle is up; building the synthetic HR data"
HERE="$(pwd -W 2>/dev/null || pwd)"
docker run --rm --network tmrkz-mover_internal -v "$HERE:/w" -w /w python:3.12-slim \
  sh -c "pip install -q --disable-pip-version-check oracledb==4.0.2 >/dev/null 2>&1 && python build_oracle_hr.py $*"
echo "[hr-demo] in TMRKZ: «إعدادات النظام» ← مصدر الموارد البشرية: tmrkz-hr-demo-oracle, 1521, FREEPDB1 (service_name), TMRKZ_HR,"
echo "          views HR_ENV_UNITS_AI and HR_PRS_EMPLOYEES_ALL; the password is ORACLE_MOVER_PASSWORD in $G/oracle_hr.env"
