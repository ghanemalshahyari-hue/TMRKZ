#!/usr/bin/env sh
# TMRKZ's synthetic enterprise directory (owner, 20 Nov 2026; ADR-094) — profile «synthetic-enterprise», DEVELOPMENT AND
# ACCEPTANCE ONLY, never in production. A Samba AD in the container «tmrkz-synthetic-ad» (image smblds/smblds, as MOVER's
# mover-test-ldap): realm TMRKZ.TEST, base DC=tmrkz,DC=test, LDAPS 636 on the application's internal network only, with a
# certificate signed by a CA generated here once (ops/hr-demo/.generated/synthetic-ad/tls, never committed), and the
# Mil* attributes added to the User class (schema/). The admin password is generated once into
# ops/hr-demo/.generated/synthetic-ad.env (never committed).
#   sh ops/hr-demo/synthetic-ad/up.sh      start, wait, apply the schema, print the values for «إعدادات التكامل»
#   sh ops/hr-demo/synthetic-ad/down.sh    stop (--wipe also removes the directory's data)
# The people: sh ops/hr-demo/synthetic-ad/load.sh [--limit N | --all] (ops/hr-demo/ad_accounts.py).
set -eu
export MSYS_NO_PATHCONV=1
cd "$(dirname "$0")"
G=../.generated
TLS="$G/synthetic-ad/tls"
ENV="$G/synthetic-ad.env"
rand() { head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c "$1"; }
docker network inspect tmrkz-mover_internal >/dev/null 2>&1 || { echo "[synthetic-ad] start TMRKZ first (sh start.sh)" >&2; exit 2; }
mkdir -p "$TLS"
if [ ! -f "$ENV" ]; then
  umask 077
  printf '# generated by ops/hr-demo/synthetic-ad/up.sh — demo only, never a production secret\nSYNTHETIC_AD_ADMIN_PASSWORD=A%s!\n' "$(rand 20)" > "$ENV"
fi
if [ ! -f "$TLS/server.crt" ]; then
  echo "[synthetic-ad] generating the test CA and the server certificate (SAN DNS:tmrkz-synthetic-ad)"
  (umask 077
   openssl req -x509 -newkey rsa:2048 -nodes -days 3650 -subj "/CN=TMRKZ Synthetic Directory CA (demo)" \
     -keyout "$TLS/ca.key" -out "$TLS/ca.crt" 2>/dev/null
   openssl req -newkey rsa:2048 -nodes -subj "/CN=tmrkz-synthetic-ad" -keyout "$TLS/server.key" -out "$TLS/server.csr" 2>/dev/null
   openssl x509 -req -in "$TLS/server.csr" -CA "$TLS/ca.crt" -CAkey "$TLS/ca.key" -CAcreateserial -days 3650 \
     -extfile tls/ext.cnf -out "$TLS/server.crt" 2>/dev/null)
  chmod 644 "$TLS/ca.crt" "$TLS/server.crt"
  chmod 644 "$TLS/server.key"      # read by samba inside the container (the folder itself is never committed)
fi
docker compose -p tmrkz-synthetic-ad --profile synthetic-enterprise --env-file "$ENV" -f compose.yml up -d
i=0
until [ "$(docker inspect -f '{{.State.Health.Status}}' tmrkz-synthetic-ad 2>/dev/null)" = healthy ]; do
  i=$((i + 1)); [ $i -gt 60 ] && { echo "[synthetic-ad] the directory did not become healthy" >&2; exit 1; }; sleep 3
done
i=0
until docker exec tmrkz-synthetic-ad sh -c 'LDAPTLS_REQCERT=demand LDAPTLS_CACERT=/tls/ca.crt ldapsearch -x -H ldaps://tmrkz-synthetic-ad:636 -b "" -s base objectClass' >/dev/null 2>&1; do
  i=$((i + 1)); [ $i -gt 40 ] && { echo "[synthetic-ad] LDAPS did not answer with the generated certificate" >&2; exit 1; }; sleep 3
done
SAM=/var/lib/samba/private/sam.ldb
if docker exec tmrkz-synthetic-ad ldbsearch -H $SAM -b CN=Schema,CN=Configuration,DC=tmrkz,DC=test '(cn=MilMainUnitId)' dn 2>/dev/null | grep -q '^dn:'; then
  echo "[synthetic-ad] schema: the Mil* attributes are already on the User class"
else
  docker exec tmrkz-synthetic-ad sh -c "ldbadd -H $SAM /schema/attributes.ldif >/dev/null && ldbmodify -H $SAM /schema/user-class.ldif >/dev/null"
  echo "[synthetic-ad] schema: MilNumber, MilLegacyNumber, MilRankName, MilOccupation, MilCurrentUnitName, MilUnitId, MilMainUnitId added to User"
fi
docker exec tmrkz-synthetic-ad ldbsearch -H $SAM -b OU=People,DC=tmrkz,DC=test -s base dn 2>/dev/null | grep -q '^dn:' \
  || docker exec tmrkz-synthetic-ad ldbadd -H $SAM /schema/people-ou.ldif >/dev/null
CA="$(cd "$TLS" && pwd)/ca.crt"
cat <<EOF
[synthetic-ad] up: tmrkz-synthetic-ad (profile synthetic-enterprise — development/acceptance only)
  in TMRKZ «إعدادات التكامل» → الدليل:
    الخادم                      tmrkz-synthetic-ad
    المنفذ / وضع التأمين        636 / ldaps
    نطاق الدخول                 tmrkz.test            (the person binds as user@tmrkz.test)
    قاعدة البحث                 DC=tmrkz,DC=test
    السمات                      «Active Directory (كما في MOVER)»: sAMAccountName, objectGUID, user, MilNumber,
                                MilRankName, MilOccupation, MilCurrentUnitName — and MilUnitId (unit ID), MilMainUnitId (main unit ID)
    شهادة الجهة المصدرة (PEM)   $CA
  the people: sh ops/hr-demo/synthetic-ad/load.sh [--limit N | --all]; their one test password: ops/hr-demo/.generated/ad-people-password
  the admin (CN=Administrator,CN=Users,DC=tmrkz,DC=test): SYNTHETIC_AD_ADMIN_PASSWORD in $ENV
EOF
